 await user.getByLabel('Motherboards',{exact:true}).selectOption('motherboard-1')
 await expect(user.getByText('El procesador y la placa tienen sockets diferentes.')).toBeVisible()
 await user.getByLabel('Procesadores',{exact:true}).selectOption('cpu-1')
 for(const [label,id] of [['Tarjetas gráficas','gpu-1'],['Memoria RAM','ram-1'],['Almacenamiento','storage-1'],['Fuentes de poder','psu-1'],['Gabinetes','case-1'],['Refrigeración','cooler-1']])await user.getByLabel(label,{exact:true}).selectOption(id)
 await expect(user.locator('.chip').filter({hasText:/^COMPATIBLE$/})).toBeVisible()
 await user.getByLabel('Nombre del ensamble').fill(buildName)
 const savedResponse=user.waitForResponse(r=>r.url().endsWith('/api/builds')&&r.request().method()==='POST')
 await user.getByRole('button',{name:'Guardar ensamble',exact:true}).click()
 const savedBody=await (await savedResponse).json() as {data:{id:string}}
 const buildId=savedBody.data.id
 await expect(user.getByRole('heading',{name:buildName,exact:true})).toBeVisible({timeout:15000})
 await user.reload()
 await expect(user.getByRole('button',{name:'Cerrar sesión',exact:true})).toBeVisible({timeout:20000})
 await expect(user.getByRole('heading',{name:buildName,exact:true})).toBeVisible({timeout:15000})
 if(process.env.E2E_RESTART_URL){const restarted=await fetch(process.env.E2E_RESTART_URL,{method:'POST'});expect(restarted.ok).toBe(true);await user.reload();await expect(user.getByRole('button',{name:'Cerrar sesión',exact:true})).toBeVisible({timeout:20000});await expect(user.getByRole('heading',{name:buildName,exact:true})).toBeVisible({timeout:15000})}
 await user.getByRole('button',{name:'Cerrar sesión',exact:true}).click()
 await expect(user.getByRole('button',{name:'Registrarse',exact:true})).toBeVisible()
 await user.goto(base+'/#/login')
 await user.getByLabel('Correo electrónico').fill(`e2e-${suffix}@example.invalid`)
 await user.getByLabel('Contraseña',{exact:true}).fill('E2E test password 123!')
 await user.getByRole('button',{name:'Iniciar sesión',exact:true}).click()
 await user.getByRole('link',{name:'Constructor',exact:true}).click()
 await expect(user.getByRole('heading',{name:buildName,exact:true})).toBeVisible({timeout:15000})
 await user.getByRole('button',{name:'Cargar configuración',exact:true}).click()
 await expect(user.getByLabel('Nombre del ensamble')).toHaveValue(buildName,{timeout:15000})
 await user.getByLabel('Nombre del ensamble').fill(buildName+' actualizado')
 await user.getByRole('button',{name:'Actualizar ensamble',exact:true}).click()
