import {test,expect} from '@playwright/test'
import {randomUUID} from 'node:crypto'
import * as OTPAuth from '../../backend/node_modules/otpauth/dist/otpauth.esm.js'
const base=process.env.E2E_BASE_URL??'http://localhost:5173'
const email=process.env.E2E_ADMIN_EMAIL,password=process.env.E2E_ADMIN_PASSWORD,secret=process.env.E2E_ADMIN_TOTP_SECRET

test('sin servidor: errores explícitos y sin acceso administrativo simulado',async({page})=>{
 await page.route('**/api/**',route=>route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({success:false,error:{message:'Servidor no disponible para esta comprobación'}})}))
 await page.goto(base)
 await expect(page.getByRole('alert')).toContainText('Servidor no disponible')
 await page.goto(base+'/#/admin')
 await expect(page.getByRole('heading',{name:'Acceso administrativo'})).toBeVisible()
 await expect(page.getByText('Se requiere una cuenta administrativa y el segundo factor verificado.')).toBeVisible()
 await page.getByRole('button',{name:'Iniciar sesión',exact:true}).last().click()
 await page.getByLabel('Correo electrónico').fill('smoke@example.invalid')
 await page.getByLabel('Contraseña',{exact:true}).fill('No real password 123!')
 await page.getByRole('button',{name:'Iniciar sesión',exact:true}).click()
 await expect(page.getByRole('alert')).toContainText('Servidor no disponible')
})

