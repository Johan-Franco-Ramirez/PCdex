const fs = require('node:fs')
const path = require('node:path')
const assert = require('node:assert/strict')
const ts = require('typescript')
const cache = new Map()
function load(file) {
 const absolute=path.resolve(file)
 if(cache.has(absolute))return cache.get(absolute)
 const exports={};cache.set(absolute,exports)
 const code=ts.transpileModule(fs.readFileSync(absolute,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText
 new Function('require','exports',code)(name=>load(path.resolve(path.dirname(absolute),name+'.ts')),exports)
 return exports
}
const {catalog}=load('src/data/components.ts'),{categories}=load('src/data/categories.ts')
const {diagnose,buildTotal}=load('src/services/builder.ts'),{parseImport}=load('src/services/admin.ts'),{searchCatalog}=load('src/services/catalog.ts')
assert.equal(categories.length,8)
assert.equal(new Set(catalog.map(i=>i.id)).size,catalog.length)
for(const category of categories)assert.ok(catalog.some(i=>i.category===category))
const good={'Procesadores':'CPU-0042',Motherboards:'MB-0001','Memoria RAM':'RAM-0001','Tarjetas gráficas':'GPU-0001','Fuentes de poder':'PSU-0001','Refrigeración':'COOL-0001'}
assert.equal(diagnose(good,catalog).filter(c=>c.status==='error').length,0)
assert.ok(diagnose({...good,Procesadores:'CPU-INTEL'},catalog).some(c=>c.label.includes('Socket')&&c.status==='error'))
assert.ok(diagnose({...good,'Memoria RAM':'RAM-DDR4'},catalog).some(c=>c.label==='Memoria RAM'&&c.status==='error'))
assert.ok(diagnose({...good,'Fuentes de poder':'PSU-0450'},catalog).some(c=>c.label==='Margen de fuente'&&c.status==='error'))
assert.equal(buildTotal({},catalog),0)
assert.equal(buildTotal({Procesadores:'CPU-0042'},catalog),1849900)
assert.equal(buildTotal({Procesadores:'DELETED'},catalog),0)
assert.equal(diagnose({},catalog).some(c=>c.status==='pass'),false)
assert.equal(searchCatalog('tarjetas graficas').length,1)
assert.equal(searchCatalog('AK400')[0].category,'Refrigeración')
assert.equal(searchCatalog('nuevo',[{...catalog[0],name:'Nuevo CPU'}]).length,1)
assert.equal(parseImport(JSON.stringify(catalog)).length,catalog.length)
assert.throws(()=>parseImport('{'))
assert.throws(()=>parseImport('[]'))
assert.throws(()=>parseImport(JSON.stringify([catalog[0],catalog[0]])))
assert.throws(()=>parseImport(JSON.stringify([{...catalog[0],price:-1} ])))
assert.throws(()=>parseImport(JSON.stringify([{...catalog[0],category:'No existe'}])))
assert.throws(()=>parseImport(JSON.stringify([{...catalog[0],specs:['bad']} ])))
assert.throws(()=>parseImport(JSON.stringify([{...catalog[0],watts:'120'}])))
assert.throws(()=>parseImport(JSON.stringify([{...catalog[0],generation:{}}])))
console.log('Comprobaciones correctas: 8 categorías, búsqueda, totales, compatibilidad simulada e importaciones válidas e inválidas.')
async function checkAI() {
 const {aiComponents}=load('src/data/aiComponents.ts')
 const {aiService,parseBudget}=load('src/services/aiService.ts')
 const items=[...catalog,...aiComponents]
 assert.equal(parseBudget('4 millones'),4000000)
 assert.equal(parseBudget('3,5 millones'),3500000)
 assert.equal(parseBudget('4.000.000 COP'),4000000)
 assert.equal(parseBudget('3500k'),3500000)
 let context={items,selection:{},budget:4000000}
 const generated=await aiService.reply('Arma un PC con presupuesto de 4 millones',context)
 assert.equal(Object.keys(generated.selection).length,8)
 assert.ok(buildTotal(generated.selection,items)<=4000000)
 assert.ok(!diagnose(generated.selection,items).some(c=>c.status==='error'))
 context={...context,selection:generated.selection}
 const change=await aiService.reply('Cambia el procesador por Ryzen',context)
 assert.equal(change.selection.Procesadores,'CPU-0042')
 assert.match(change.content,/Atención/)
 const removed=await aiService.reply('Quita la gráfica',context)
 assert.equal(removed.selection['Tarjetas gráficas'],undefined)
 assert.equal(removed.selection.Procesadores,context.selection.Procesadores)
 const budget=await aiService.reply('Mi presupuesto es 2 millones',context)
 assert.equal(budget.budget,2000000)
 const low=await aiService.reply('Arma un PC con presupuesto de 1 millón',context)
 assert.match(low.content,/Exceso/)
 const empty=await aiService.reply('Arma un PC',{...context,items:[]})
 assert.deepEqual(empty.selection,{})
 assert.match(empty.content,/no permite/)
 const diagnosis=await aiService.reply('Verifica compatibilidad',context)
 assert.match(diagnosis.content,/Socket/)
 console.log('PCdex AI: generación completa, límite de presupuesto, cambios, eliminación, diagnóstico y catálogo vacío correctos.')
}
checkAI().catch(error=>{console.error(error);process.exitCode=1})
