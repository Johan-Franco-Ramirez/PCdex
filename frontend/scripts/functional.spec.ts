 await user.goto(base+'/#/register')
 await user.getByLabel('Nombre de usuario').fill('Explorador '+suffix)
 await user.getByLabel('Correo electrónico').fill(`e2e-${suffix}@example.invalid`)
 await user.getByLabel('Contraseña',{exact:true}).fill('E2E test password 123!')
 await user.getByLabel('Confirmar contraseña').fill('E2E test password 123!')
 await user.getByRole('button',{name:'Crear cuenta',exact:true}).click()
 await user.getByRole('link',{name:'Catálogo',exact:true}).click()
 await expect(user.getByText('Ficha de prueba editada desde navegador '+suffix,{exact:true})).toBeVisible()
 await user.getByRole('link',{name:'Constructor',exact:true}).click()
 await user.getByLabel('Presupuesto máximo (COP)').fill('5000000')
